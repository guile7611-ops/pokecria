import assert from 'node:assert/strict';
import {once} from 'node:events';
import {chromium} from '@playwright/test';
import {server} from '../server.mjs';

const externalUrl=process.env.SMOKE_URL;
if(!externalUrl){server.listen(0,'127.0.0.1');await once(server,'listening');}
const browser=await chromium.launch({headless:true});
try{
  const url=externalUrl||`http://127.0.0.1:${server.address().port}/`;
  const first=await browser.newPage(),second=await browser.newPage();
  await Promise.all([first.goto(url),second.goto(url)]);
  const join=(page,nick,spawnEpoch)=>page.evaluate(async({nick,spawnEpoch})=>{
    const {cloud}=await import('/cloud-client.js');
    const {RealtimeOnline}=await import('/realtime-online.js');
    cloud.session={user:{id:nick}};
    window.smokeEvents=[];
    window.smokePositions=[];
    window.smokeOnline=new RealtimeOnline({world:({spawnEpoch})=>{window.smokeEpoch=spawnEpoch;},roster:({players})=>{const friend=players.find(player=>player.nick==='SmokeA');if(friend)window.smokePositions.push(friend.x);},'pvp-hit':event=>window.smokeEvents.push(event),'pvp-status':event=>window.smokeEvents.push(event),'boss-state':event=>window.smokeEvents.push(event),'wild-hit':event=>window.smokeEvents.push(event),'wild-kill':event=>window.smokeEvents.push(event),'wild-state':event=>window.smokeEvents.push(event)});
    await window.smokeOnline.join({nick,pokemon:'bulbasaur',spawnEpoch});
    return window.smokeOnline.id;
  },{nick,spawnEpoch});
  const firstId=await join(first,'SmokeA',123);
  const secondId=await join(second,'SmokeB',124);
  await Promise.all([first.waitForFunction(id=>window.smokeOnline.players.some(player=>player.id===id),secondId,{timeout:12000}),second.waitForFunction(id=>window.smokeOnline.players.some(player=>player.id===id),firstId,{timeout:12000})]);
  const a=await first.evaluate(()=>({players:window.smokeOnline.players.map(p=>p.id),epoch:window.smokeOnline.state.spawnEpoch}));
  const b=await second.evaluate(()=>({players:window.smokeOnline.players.map(p=>p.id),epoch:window.smokeOnline.state.spawnEpoch}));
  assert.ok(a.players.includes(secondId)&&b.players.includes(firstId));
  assert.equal(a.epoch,0);assert.equal(b.epoch,0);
  await first.evaluate(async()=>{window.smokeOnline.update({x:900,y:560,hp:100,maxHp:100});await window.smokeOnline.track(true);});
  await second.evaluate(async()=>{window.smokeOnline.update({x:960,y:560,hp:100,maxHp:100});await window.smokeOnline.track(true);});
  await Promise.all([first.waitForFunction(id=>window.smokeOnline.players.find(p=>p.id===id)?.x===960,secondId),second.waitForFunction(id=>window.smokeOnline.players.find(p=>p.id===id)?.x===900,firstId)]);
  await first.evaluate(async()=>{for(const x of [752,800,848,896,944,992,1040,1088]){window.smokeOnline.update({x,y:560,moving:true});await new Promise(resolve=>setTimeout(resolve,180));}});
  await second.waitForFunction(id=>window.smokeOnline.players.find(p=>p.id===id)?.x===1088,firstId);
  assert.ok(await second.evaluate(()=>new Set(window.smokePositions.filter(x=>x>=752&&x<=1088)).size>=4),'positions must continue across the bridge');
  await second.evaluate(id=>{const online=window.smokeOnline;window.smokeReceive=online.receive.bind(online);online.receive=message=>{if(message.type==='player-state'&&message.from===id)return;window.smokeReceive(message);};},firstId);
  await first.evaluate(async()=>{window.smokeOnline.update({x:700,y:560,moving:false});await new Promise(resolve=>setTimeout(resolve,1300));window.smokeOnline.update({x:700,y:560,moving:false});});
  await second.waitForFunction(id=>window.smokeOnline.players.find(player=>player.id===id)?.x===700,firstId,{timeout:15000});
  await second.evaluate(()=>{window.smokeOnline.receive=window.smokeReceive;});
  await first.evaluate(()=>window.smokeOnline.update({x:900,y:560,moving:false}));
  await second.waitForFunction(id=>window.smokeOnline.players.find(p=>p.id===id)?.x===900,firstId);
  const retained=await second.evaluate(id=>{const online=window.smokeOnline,original=online.channel.presenceState;online.channel.presenceState=()=>({});online.roster();const visible=online.players.some(player=>player.id===id);online.channel.presenceState=original;return visible;},firstId);
  assert.equal(retained,true,'a brief presence gap must not hide a remote player');
  await first.evaluate(()=>window.smokeOnline.request('wild-hit',{uid:999999,damage:17,hp:88,maxHp:105}));
  await second.waitForFunction(()=>window.smokeEvents.some(event=>event.type==='wild-hit'&&event.uid===999999&&event.damage===17));
  await second.evaluate(()=>window.smokeOnline.send('wild-sync-request',{}));
  await second.waitForFunction(()=>window.smokeEvents.some(event=>event.type==='wild-state'&&event.uid===999999));
  await first.evaluate(()=>window.smokeOnline.request('wild-kill',{uid:999999,xp:0}));
  await second.waitForFunction(()=>window.smokeEvents.some(event=>event.type==='wild-kill'&&event.uid===999999));
  await first.evaluate(id=>window.smokeOnline.request('pvp',{targetId:id}),secondId);
  await second.waitForFunction(()=>window.smokeEvents.some(event=>event.type==='pvp-hit'));
  assert.ok(await second.evaluate(()=>window.smokeOnline.state.hp<100));
  const hpAfterAttack=await second.evaluate(()=>window.smokeOnline.state.hp);
  await first.evaluate(()=>window.smokeOnline.request('skill',{ability:'growl',x:960,y:560}));
  await second.waitForFunction(()=>window.smokeEvents.some(event=>event.type==='pvp-status'&&event.ability==='growl'));
  assert.equal(await second.evaluate(()=>window.smokeOnline.state.hp),hpAfterAttack);
  await first.evaluate(()=>window.smokeOnline.request('wild-hit',{uid:999998,damage:30,isBoss:true,hp:390,maxHp:420,respawn:45}));
  await second.waitForFunction(()=>window.smokeEvents.some(event=>event.uid===999998&&event.hp===390));
  await first.evaluate(id=>window.smokeOnline.request('guild/invite',{targetId:id}),secondId);
  await second.waitForFunction(()=>window.smokeOnline.pendingInvite?.fromNick==='SmokeA');
  await second.evaluate(()=>window.smokeOnline.request('guild/reply',{accept:true}));
  await first.waitForFunction(()=>!!window.smokeOnline.guildId);
  await first.waitForFunction(id=>window.smokeOnline.players.find(player=>player.id===id)?.guildId===window.smokeOnline.guildId,secondId);
  assert.equal(await first.evaluate(()=>window.smokeOnline.guildId),await second.evaluate(()=>window.smokeOnline.guildId));
  await assert.rejects(first.evaluate(id=>window.smokeOnline.request('pvp',{targetId:id}),secondId),/Membros da guilda/);
  await Promise.all([first.evaluate(()=>window.smokeOnline.leave()),second.evaluate(()=>window.smokeOnline.leave())]);
  console.log('Realtime: duas sessões compartilham presença, mapa, PvP, guilda e vida do boss.');
}finally{await browser.close();if(!externalUrl){server.close();await once(server,'close');}}
